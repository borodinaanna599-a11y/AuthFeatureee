fun getCommitCount(): Int {
    return try {
        val process = ProcessBuilder(
            "git", "rev-list", "--count", "HEAD"
        )
            .directory(rootProject.projectDir)
            .redirectErrorStream(true)
            .start()

        val count = process.inputStream
            .bufferedReader()
            .readText()
            .trim()

        process.waitFor()
        count.toInt().coerceAtLeast(1)
    } catch (e: Exception) {
        1
    }
}

